/**
 * Server-side authorisation.
 *
 * Client checks are convenience, not security. The same permission model is
 * compiled into Firestore Security Rules below. Rules read a denormalised
 * `perms` array on each user document — that array is recomputed and written
 * by `syncUserPermissions()` whenever a role or an assignment changes, so a
 * client can never grant itself a permission it does not hold.
 */
